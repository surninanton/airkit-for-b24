import { chromium } from '@playwright/test';
const [,, url, out, w = '1280', actions = ''] = process.argv;
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: +w, height: 900 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto(url); await p.waitForTimeout(900);
if (actions) await new Function('p', `return (async () => { ${actions} })()`)(p);
else await p.screenshot({ path: out, fullPage: true });
console.log('errors', JSON.stringify(errs), 'overflow', await p.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth));
await b.close();
